import type { Recommendation } from '../progression';

export type EvidenceLevel = 'limited' | 'moderate' | 'stronger';
export type Fact = { id: string; label: string; value: number | string | null; unit?: string };
export type Observation = { id: string; tone: 'positive' | 'attention' | 'info'; title: string; detail: string; facts: string[]; exercise?: string };
export type CriterionStatus = 'met' | 'unmet' | 'unknown';
export type Criterion = { id: string; label: string; status: CriterionStatus; detail: string };
export type SetView = { index: number; weight: number; reps: number; rir: number | null; meetsMin: boolean; reachesMax: boolean };
export type SessionPoint = { sessionId: string; date: string; name: string; topWeight: number; totalReps: number; sets: number; estimated1RM: number | null; loadVolume: number; comparable: boolean };
export type TrendKind = 'none' | 'two-session' | 'improving' | 'declining' | 'mixed' | 'possible-plateau';
export type Trend = { kind: TrendKind; sessions: number; totals: number[]; dates: string[]; summary: string };
export type Comparison = { sessionId: string; date: string; sets: { weight: number; reps: number }[]; totalReps: number; topWeight: number; comparable: boolean; differences: string[]; summary: string };
export type ActionLabel = Recommendation['action'];
export type NextTarget = {
  action: ActionLabel;
  actionLabel: string;
  weight: number | null;
  repMin: number;
  repMax: number;
  sets: number;
  rirMin: number;
  rirMax: number;
  /** Rest durations are not logged by REPWISE, so no rest interval is prescribed. */
  rest: null;
  immediateGoal: string;
  progression: string;
  explanation: string;
  level: EvidenceLevel;
  missing: string[];
};
export type EvidenceStatement = { observed: string[]; rules: string[]; assumptions: string[]; limitations: string[] };
export type ExerciseAnalysis = {
  performedId: string;
  exerciseId: string;
  name: string;
  muscle: string;
  secondary: string[];
  equipment: string | null;
  loadKind: 'external' | 'bodyweight';
  planned: number;
  completed: number;
  notCompleted: number;
  repMin: number;
  repMax: number;
  sets: SetView[];
  totalReps: number;
  topWeight: number;
  loadVolume: number;
  volumeLabel: string;
  setsMeetingMin: number;
  setsAtMax: number;
  rir: { recorded: number; of: number; average: number | null };
  estimated1RM: number | null;
  previous: Comparison | null;
  previousComparable: Comparison | null;
  comparableSessions: number;
  trend: Trend;
  history: SessionPoint[];
  records: { load: boolean; reps: boolean; baseline: boolean; detail: string[] };
  flags: { pain: boolean; techniqueConcern: boolean; override: number | null };
  criteria: Criterion[];
  ruleId: string;
  decision: Recommendation;
  narrative: string;
  observations: Observation[];
  next: NextTarget;
  evidence: EvidenceStatement;
  evidenceLevel: EvidenceLevel;
  evidenceBasis: string;
  facts: Fact[];
};
export type MuscleRow = { muscle: string; session: number; thisWeek: number; lastWeek: number; fourWeekAverage: number; indirectThisWeek: number };
export type SessionAnalysis = {
  schemaVersion: number;
  engineVersion: string;
  fingerprint: string;
  status: 'complete' | 'draft';
  overview: {
    sessionId: string;
    name: string;
    date: string;
    duration: { available: false; note: string };
    exercisesLogged: number;
    exercisesWithWorkingSets: number;
    plannedSets: number;
    completedSets: number;
    countedTowardPlan: number;
    extraSets: number;
    totalReps: number;
    volume: { value: number; label: string; included: string[]; excluded: string[] };
    prCount: number;
    outcomes: Record<string, number>;
    recovery: { available: boolean; notes: string[] };
    previousSession: null | { id: string; name: string; date: string; completedSets: number; totalReps: number; volume: number };
    comparisonNote: string;
  };
  exercises: ExerciseAnalysis[];
  wentWell: Observation[];
  needsAttention: Observation[];
  plan: { exercise: string; performedId: string; target: NextTarget }[];
  muscles: { rows: MuscleRow[]; convention: string };
  dataGaps: string[];
  criteria: Record<string, string>;
  facts: Fact[];
};
